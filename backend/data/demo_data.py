def generate_sample_telemetry_trace(acc_z_peak: float, is_bump: bool = True) -> List[Dict[str, Any]]:
    trace = []
    for i in range(30):
        t = i * 0.05
        if is_bump and 12 <= i <= 18:
            phase = (i - 12) / 6.0
            acc_z = 1.0 + (acc_z_peak - 1.0) * (1.0 - abs(phase - 0.5) * 2.0)
            acc_x = (phase - 0.5) * 0.4
            acc_y = (phase - 0.5) * 0.3
            jerk = (acc_z - 1.0) * 15.0
            db = 42.0 + (acc_z - 1.0) * 25.0
        else:
            acc_z = 1.0 + 0.04 * ((i % 3) - 1)
            acc_x = 0.02 * ((i % 2) - 0.5)
            acc_y = 0.01 * ((i % 4) - 1.5)
            jerk = 0.4
            db = 40.0 + (i % 3)

        trace.append({
            "time_sec": round(t, 2),
            "acc_x": round(acc_x, 3),
            "acc_y": round(acc_y, 3),
            "acc_z": round(acc_z, 3),
            "vertical_jerk": round(jerk, 2),
            "acoustic_db": round(db, 1),
        })
    return trace


